"""Заготовка провайдера kassa.ai.

Публичной документации у сервиса нет, поэтому здесь нет ни одного адреса, ни
одного имени поля и никакой схемы подписи: выдуманный код, который выглядит
рабочим, однажды уедет в бой и сломается на живом покупателе, а явная ошибка
ломается только у нас и сразу. Реализация появится, когда заказчик пришлёт
документацию.

Четыре вопроса, которые нужно задать документации, — ровно то, чего не хватает
для замены этой заготовки на живой клиент:

1. Создание платежа: метод и путь эндпоинта, обязательные поля тела запроса
   (сумма — в рублях или в копейках? валюта? свой номер заказа — есть ли поле
   вроде `payload`, которое вернётся обратно в callback?), а в ответе — где
   лежат идентификатор транзакции и ссылка на оплату.
2. Проверка статуса: метод и путь эндпоинта, полный список возможных состояний
   и что именно из них считается оплатой, отменой и возвратом — это нужно,
   чтобы собрать STATUS_MAP на наши PayStatus.
3. Авторизация запросов: заголовки или подпись — куда подставляются
   merchant_id и secret, участвует ли в подписи тело запроса, есть ли метка
   времени и окно её годности.
4. Callback: адрес, который сервис дёргает, состав полей и — главное — есть ли
   криптографическая подпись и как она считается. Если подписи нет (как у
   Platega), callback остаётся только сигналом «сходи проверь», а решение об
   оплате принимается по ответу эндпоинта из пункта 2.
"""

from __future__ import annotations

import logging

from bot.payments.base import Invoice, PaymentMethod, ProviderError, StatusResult

log = logging.getLogger(__name__)

NAME = "kassa"

# Текст один на оба метода: снаружи важно не «какой вызов не дошёл», а то, что
# интеграции нет вообще и починить это можно только документацией.
NOT_IMPLEMENTED = (
    "Интеграция kassa.ai не заполнена: нужна документация API. "
    "Оплата через kassa.ai недоступна."
)


class KassaProvider:
    name = NAME

    def __init__(
        self,
        base_url: str,
        merchant_id: str,
        secret: str,
        return_url: str,
        failed_url: str,
    ) -> None:
        # Настройки сохраняются, хотя пока не используются: они уже известны из
        # конфига, и когда документация придёт, править придётся только тело
        # методов, а не проводку от Settings до провайдера.
        self._base_url = base_url.rstrip("/")
        self._merchant_id = merchant_id
        self._secret = secret
        self._return_url = return_url
        self._failed_url = failed_url

    # --- интерфейс провайдера ---------------------------------------------

    def methods(self) -> list[PaymentMethod]:
        """Ни одного способа оплаты.

        Пустой список — единственный честный ответ: кнопка, после которой
        покупатель получает ошибку, читается как поломка магазина.
        """
        return []

    async def create_invoice(
        self,
        order_id: int,
        amount_kop: int,
        description: str,
        method_code: str,
        user_id: int,
        username: str | None = None,
    ) -> Invoice:
        log.error("Попытка выставить счёт через kassa.ai, заказ %s", order_id)
        raise ProviderError(NOT_IMPLEMENTED)

    async def fetch_status(self, txn_id: str) -> StatusResult:
        log.error("Попытка проверить статус kassa.ai, транзакция %s", txn_id)
        raise ProviderError(NOT_IMPLEMENTED)

    async def close(self) -> None:
        """Закрывать нечего — сетевой сессии нет.

        Метод всё равно нужен: реестр закрывает провайдеров одинаково, и
        отсутствие `close` уронило бы выключение бота.
        """
        return None
