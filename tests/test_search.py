"""Поиск товаров по названию: опечатки, перестановка слов, забытая раскладка.

Проверяется наблюдаемое поведение — какие id и в каком порядке вернулись, —
а не устройство весов. Конкретные числа rapidfuzz намеренно нигде не
зашиты: подтянут библиотеку, веса поедут, а обещания магазину останутся те же.
"""

from __future__ import annotations

import pytest

from bot.services.search import DEFAULT_THRESHOLD, normalize, rank, switch_layout

# Каталог подписочного магазина: русские и латинские названия вперемешку —
# так он и выглядит у заказчика.
CATALOG: list[tuple[int, str]] = [
    (1, "Нетфликс Премиум 12 месяцев"),
    (2, "Нетфликс"),
    (3, "Spotify Premium"),
    (4, "YouTube Premium 6 месяцев"),
]


# --- нормализация ---------------------------------------------------------


def test_normalize_strips_case_punctuation_and_extra_spaces() -> None:
    assert normalize("  Netflix —  12 мес.  ") == "netflix 12 мес"


def test_normalize_maps_yo_to_e() -> None:
    """«Ёжик» и «ежик» покупатель набирает как попало."""
    assert normalize("ЁЖИК") == normalize("ежик") == "ежик"


# --- раскладка ------------------------------------------------------------


def test_switch_layout_latin_to_cyrillic() -> None:
    assert switch_layout("Ytnabrc") == "Нетфикс"


def test_switch_layout_cyrillic_to_latin() -> None:
    assert switch_layout("туеадшч") == "netflix"


def test_switch_layout_is_reversible() -> None:
    """Таблица работает в обе стороны, значит два прогона дают исходную строку."""
    assert switch_layout(switch_layout("нетфликс")) == "нетфликс"
    assert switch_layout(switch_layout("Netflix")) == "Netflix"


# --- ранжирование ---------------------------------------------------------


def test_typo_still_finds_product() -> None:
    """«нетфликc» — латинская c вместо кириллической, глазом не отличить."""
    items = [(10, "Spotify Premium"), (11, "Нетфликс")]
    assert rank("нетфликc", items) == [11]


def test_swapped_words_still_find_product() -> None:
    """Покупатель называет товар своими словами, порядок слов не совпадает."""
    items = [(10, "Spotify Premium"), (11, "Нетфликс Премиум")]
    assert rank("премиум нетфликс", items) == [11]


def test_forgotten_layout_latin_keys() -> None:
    """«Ytnabrc» — это «Нетфикс», набранный при английской раскладке."""
    items = [(10, "Spotify Premium"), (11, "Нетфликс")]
    assert rank("Ytnabrc", items) == [11]


def test_forgotten_layout_cyrillic_keys() -> None:
    """Обратная сторона: «туеадшч» — это «netflix», набранный в ЙЦУКЕН."""
    items = [(10, "Spotify Premium"), (11, "Netflix Premium 12 месяцев")]
    assert rank("туеадшч", items) == [11]


def test_case_and_yo_are_ignored() -> None:
    items = [(7, "ежик")]
    assert rank("ЁЖИК", items) == [7]


def test_alien_query_returns_nothing() -> None:
    """Чужой запрос лучше вернуть пустым, чем случайным товаром."""
    assert rank("холодильник", CATALOG) == []


@pytest.mark.parametrize("query", ["", "   ", "!!!", "—", ".", ",", "[", ";", "'", "`"])
def test_empty_query_returns_nothing(query: str) -> None:
    """Пустой запрос — это не «показать всё».

    Знаки препинания в списке не для красоты: «.», «,», «[», «;», «'», «`» —
    это клавиши кириллических «ю», «б», «х», «ж», «э», «ё», и запрос из одной
    точки, перевёрнутый в раскладку, ищет по каталогу букву «ю».
    """
    assert rank(query, [(1, "Яндекс Плюс"), (2, "Хабр"), *CATALOG]) == []


def test_layout_variant_does_not_drag_alien_product() -> None:
    """«ютуб» не должен приводить Netflix.

    Кириллические «ю» и «б» на латинской раскладке — это «.» и «,»;
    нормализация их срезает, и от запроса остаётся огрызок «ne», который
    оказывается подстрокой «netflix» и забирает 100 за точное вхождение.
    Чужой товар на первом месте хуже пустой выдачи.
    """
    items = [(1, "Netflix Premium 12 месяцев"), (2, "YouTube Premium 6 месяцев")]
    assert 1 not in rank("ютуб", items)


def test_forgotten_layout_survives_punctuation_keys() -> None:
    """Обратная сторона того же: «gk.c» — это «плюс», точка тут буква «ю».

    Проверка держит границу: отбрасывать надо только переворот, теряющий
    буквы, а не любой переворот со знаками препинания.
    """
    items = [(10, "Spotify Premium"), (11, "Яндекс Плюс")]
    assert rank("Zyltrc gk.c", items) == [11]


def test_exact_match_outranks_longer_similar_name() -> None:
    """Короткое точное совпадение обязано быть выше длинного похожего.

    По token_set_ratio «Netflix Premium 12 месяцев» получает те же 100, что и
    «Netflix», и при устойчивой сортировке всплыло бы первым просто потому,
    что раньше стоит в списке. Искали именно «Netflix».
    """
    items = [(1, "Netflix Premium 12 месяцев"), (2, "Netflix")]
    assert rank("Netflix", items)[0] == 2


def test_exact_match_outranks_perfect_fuzzy_match() -> None:
    """Первый проход обязан обгонять второй, а не только совпадать с ним.

    «Премиум Нетфликс» — та же перестановка слов, token_set_ratio даёт ей
    честные 100, столько же, сколько точному вхождению. Названия одной длины,
    перестановка идёт в списке первой — если проходы не разделены, наверх
    всплывёт она, а искали «Нетфликс Премиум» дословно.
    """
    items = [(1, "Премиум Нетфликс"), (2, "Нетфликс Премиум")]
    assert rank("нетфликс премиум", items)[0] == 2


def test_limit_caps_result_length() -> None:
    items = [(index, f"Нетфликс Премиум {index}") for index in range(1, 11)]
    assert len(rank("нетфликс", items, limit=3)) == 3


def test_limit_cuts_after_ranking_not_before() -> None:
    """Обрезка идёт по отранжированному списку, а не по каталогу.

    Если сначала взять первые limit товаров и ранжировать их, самый точный
    товар потеряется просто потому, что лежит в каталоге ниже. Длина выдачи
    при этом останется правильной — на глаз ошибка не видна.
    """
    items = [(1, "Нетфликс Премиум 12 месяцев"), (2, "Нетфликс Премиум"), (3, "Нетфликс")]
    assert rank("нетфликс", items, limit=1) == [3]


def test_default_limit_is_thirty() -> None:
    """Выдача по умолчанию — тридцать товаров: столько влезает в сообщение."""
    items = [(index, f"Нетфликс {index}") for index in range(1, 41)]
    assert len(rank("нетфликс", items)) == 30


def test_equal_weight_keeps_input_order() -> None:
    """При равном весе порядок items не перемешивается.

    id намеренно идут по убыванию: если сортировать по id вместо позиции в
    списке, тест это заметит. Порядок items задаёт вызывающий (у него это
    `sort_order` каталога), и поиск не вправе его переставлять.
    """
    items = [(9, "Нетфликс Премиум"), (4, "Нетфликс Премиум")]
    assert rank("нетфликс премиум", items) == [9, 4]


def test_fuzzy_pass_ignores_title_length() -> None:
    """Среди нечётких совпадений длина названия ничего не решает.

    Оба названия получают одинаковый вес и ни одно не содержит запрос
    целиком, значит порядок берётся из items. Тай-брейк по длине живёт только
    в проходе точных вхождений: там короткое название и правда ближе к
    запросу, а здесь оно ничем не лучше.
    """
    items = [(9, "Нетфликс Премиум 12 месяцев"), (4, "Нетфликс Премиум")]
    assert rank("премиум нетфликс", items) == [9, 4]


def test_swapped_words_outrank_partial_string_match() -> None:
    """Перестановка слов весит больше, чем случайный кусок строки.

    «Премиум Фликер Подписка» похож на запрос буквами, «Нетфликс Премиум 12
    месяцев» — словами. Искали товар, а не строку, поэтому наверх идёт второй.
    """
    items = [(1, "Премиум Фликер Подписка"), (2, "Нетфликс Премиум 12 месяцев")]
    assert rank("премиум нетфликс", items)[0] == 2


def test_threshold_keeps_typos_and_drops_lookalikes() -> None:
    """Порог стоит между настоящей опечаткой и посторонним товаром.

    «нитфлекс» — две опечатки, но это он; «Фликер» — чужой товар, похожий
    буквами. Порог, задранный вверх, потеряет первое; уроненный вниз —
    притащит второе. Тест держит обе границы.
    """
    catalog = [(1, "Нетфликс"), (2, "Фликер")]
    assert rank("нитфлекс", catalog) == [1]
    assert rank("нетфликс", catalog) == [1]


def test_broken_title_never_surfaces() -> None:
    """Товар, от названия которого после нормализации ничего не осталось,
    в выдачу не попадает даже при нулевом пороге."""
    items = [(1, "—"), (2, "Нетфликс")]
    assert rank("нетфликс", items, threshold=0) == [2]


def test_threshold_is_what_keeps_the_catalog_out() -> None:
    """Отдельная защита: выдачу режет именно порог, а не везение с весами.

    Если порог однажды снимут или уронят в ноль, поиск начнёт возвращать весь
    каталог на любой запрос — «Холодильник» в ответ на «нетфликс» никто не
    заметит на глаз, а конверсия просядет. Тест фиксирует оба состояния:
    при threshold=0 чужой товар в выдаче есть, при штатном пороге — нет.
    """
    items = [(2, "Нетфликс"), (99, "Холодильник Атлант двухкамерный")]

    assert rank("нетфликс", items, threshold=0) == [2, 99]
    assert rank("нетфликс", items, threshold=DEFAULT_THRESHOLD) == [2]


# --- кириллица против латиницы ----------------------------------------------
#
# Магазин продаёт иностранные сервисы русским покупателям, и «нетфликс» —
# это не опечатка и не забытая раскладка, а самый обычный способ набрать
# название. Переключение раскладки здесь не спасает: оно переводит «Ytnabrc»
# в «нетфликс», а до «Netflix» остаётся ровно один шаг — транслитерация.


@pytest.mark.parametrize(
    ("query", "title"),
    [
        ("нетфликс", "Netflix Premium — 1 месяц"),
        ("чатгпт", "ChatGPT Plus — 1 месяц"),
        ("чат гпт", "ChatGPT Plus — 1 месяц"),
        ("спотифай", "Spotify Premium — 3 месяца"),
        ("курсор", "Cursor Pro — 1 месяц"),
        ("мидджорни", "Midjourney Basic — 1 месяц"),
    ],
)
def test_cyrillic_spelling_finds_latin_title(query: str, title: str) -> None:
    assert rank(query, [(1, title)]) == [1]


def test_latin_query_finds_cyrillic_title() -> None:
    """И наоборот: название по-русски, запрос латиницей."""
    assert rank("netflix", [(1, "Нетфликс Премиум — 1 месяц")]) == [1]


def test_cyrillic_spelling_survives_a_typo() -> None:
    """Кириллическое написание с опечаткой — всё ещё тот же товар."""
    assert rank("нетфлкс", [(1, "Netflix Premium")]) == [1]
    assert rank("нктфликс", [(1, "Netflix Premium")]) == [1]


def test_one_shared_word_is_not_a_match() -> None:
    """Общее слово не делает товары похожими.

    Это защита от побочного эффекта транслитерации. «премиум» совпадает
    со «Spotify Premium» на все сто, и если считать средний вес по словам,
    запрос «премиум нетфликс» вытащит Spotify — при том что человек искал
    ровно другое. Значимое слово запроса, не нашедшее пары, обязано снимать
    кандидата целиком.
    """
    items = [(10, "Spotify Premium"), (11, "Netflix Premium")]

    assert rank("премиум нетфликс", items) == [11]
    assert rank("spotify премиум", items) == [10]
    # А запрос из одного общего слова честно находит оба.
    assert sorted(rank("premium", items)) == [10, 11]


def test_short_words_do_not_veto_a_match() -> None:
    """Служебные короткие слова не должны отсекать товар.

    «1» и «мес» не найдут себе пары в названии, и если требовать пару от
    каждого слова без разбора, обычный запрос перестанет работать.
    """
    assert rank("netflix 1 мес", [(1, "Netflix Premium — 12 месяцев")]) == [1]
